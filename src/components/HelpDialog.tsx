import { Modal } from './ui/Modal';

export function HelpDialog({ open, onClose }: { open: boolean; onClose: () => void }) {
  return (
    <Modal open={open} title="帮助与统计口径" onClose={onClose} wide>
      <div className="prose">
        <h2>这是什么产品</h2>
        <p>
          X Account Insight（X 账号数据体检）帮助你分析自己 X 账号的运营表现：曝光、互动、粉丝变化、发帖频率与时间段表现。
          它只分析你主动导入的 CSV 数据，所有计算在浏览器本地完成，透明、可复核。
        </p>
        <h2>需要什么数据</h2>
        <ul>
          <li>
            <strong>Content CSV（内容数据）</strong>：X 分析页「内容 Content」标签页导出的单帖表现数据（帖子正文、时间、曝光、点赞、回复、转发、收藏等）。
          </li>
          <li>
            <strong>Overview CSV（每日汇总）</strong>：X 分析页「概览 Overview」标签页导出的每日整体数据（每日曝光、主页访问、新增/取消关注等）。
          </li>
        </ul>
        <p>可以只导入其中一类：只导入 Content 可分析单帖与曝光；只导入 Overview 可分析每日汇总；两者都导入可获得最完整结果。</p>
        <h2>统计口径</h2>
        <ul>
          <li>
            <strong>互动量</strong> = 按文件实际存在的字段求和：点赞 + 回复 + 转发 + 引用 + 收藏（不重复计数）。
            若文件没有任何互动分量字段，则使用文件自带的互动总量字段。
          </li>
          <li>
            <strong>可计算互动率</strong> = 可用互动量合计 ÷ 曝光量合计 × 100%。这是本工具按可用字段计算的指标，
            不保证与 X 分析页面的所有口径完全一致；分母为 0、缺失或数据不完整时显示「无法计算」。
          </li>
          <li>
            <strong>净增粉丝</strong> = 新增关注 − 取消关注（两者齐备才计算；仅有其一则明确标注为部分数据）。
          </li>
          <li>
            <strong>周期变化率</strong> =（当前周期数值 − 对比周期数值）÷ 对比周期数值 × 100%；对比基数为 0 或缺失时显示「无法比较」。
          </li>
          <li>
            <strong>缺失值处理</strong>：明确区分「真实为 0」「未导出」「缺失」「解析错误」「无法计算」，不会把缺失当作 0 填充。
          </li>
        </ul>
        <h2>能得出什么结论</h2>
        <p>
          所有结论均来自你导入的数据：曝光趋势、互动变化、发帖节奏、时间段表现、数据完整性与样本是否充分。
          本工具<strong>不检测、不判定</strong>账号是否被限流、降权、封禁或列入风控——这些需要平台内部数据，
          仅凭 CSV 无法确认。报告中出现「观察到下降」只是数据现象，不等于平台对账号采取了任何措施。
        </p>
        <h2>演示数据</h2>
        <p>「加载模拟演示数据」生成的是程序合成的数据，明确标注为模拟数据，与真实数据严格隔离，可用于体验全部功能。</p>
      </div>
    </Modal>
  );
}
